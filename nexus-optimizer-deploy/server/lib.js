function audit(actorId, action, target, meta) {
  db.prepare(
    "INSERT INTO audit (actor_id, action, target, meta, created_at) VALUES (?, ?, ?, ?, ?)"
  ).run(
    actorId == null ? null : Number(actorId),
    String(action),
    target == null ? null : String(target),
    meta == null ? null : JSON.stringify(meta),
    nowIso()
  );
}

/* ------------------------------------------------------------------ crypto */

function hashPassword(password) {
  const salt = crypto.randomBytes(16);
  const hash = crypto.scryptSync(String(password), salt, 64, { N: 16384, r: 8, p: 1 });
  return "scrypt$16384$8$1$" + salt.toString("base64") + "$" + hash.toString("base64");
}

function verifyPassword(password, stored) {
  if (!stored || typeof stored !== "string") return false;
  const parts = stored.split("$");
  if (parts.length !== 6 || parts[0] !== "scrypt") return false;
  const salt = Buffer.from(parts[4], "base64");
  const expected = Buffer.from(parts[5], "base64");
  try {
    const actual = crypto.scryptSync(String(password), salt, expected.length, {
      N: Number(parts[1]),
      r: Number(parts[2]),
      p: Number(parts[3]),
    });
    return crypto.timingSafeEqual(actual, expected);
  } catch (error) {
    return false;
  }
}

function randomToken(bytes) {
  return crypto.randomBytes(bytes || 32).toString("base64url");
}

function sha256(value) {
  return crypto.createHash("sha256").update(String(value)).digest("hex");
}

function normalizeCode(value) {
  return String(value || "").toUpperCase().replace(/[^A-Z0-9]/g, "");
}

function hashCode(value) {
  return sha256(normalizeCode(value));
}

function makeCode(prefix, groups, groupSize) {
  const alphabet = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789";
  const parts = [];
  const bytes = crypto.randomBytes(groups * groupSize);
  let offset = 0;
  for (let g = 0; g < groups; g += 1) {
    let part = "";
    for (let i = 0; i < groupSize; i += 1) {
      part += alphabet[bytes[offset] % alphabet.length];
      offset += 1;
    }
    parts.push(part);
  }
  return prefix + "-" + parts.join("-");
}

function codeHint(code) {
  const normalized = normalizeCode(code);
  return "…" + normalized.slice(-4);
}

function safeEqual(a, b) {
  const left = Buffer.from(String(a || ""));
  const right = Buffer.from(String(b || ""));
  return left.length === right.length && left.length > 0 && crypto.timingSafeEqual(left, right);
}

/* ------------------------------------------------------------------ cookies */

function parseCookies(header) {
  const out = {};
  if (!header) return out;
  for (const piece of String(header).split(";")) {
    const index = piece.indexOf("=");
    if (index < 0) continue;
    const key = piece.slice(0, index).trim();
    const value = piece.slice(index + 1).trim();
    if (key) {
      try {
        out[key] = decodeURIComponent(value);
      } catch (error) {
        out[key] = value;
      }
    }
  }
  return out;
}

function addCookie(res, cookie) {
  const previous = res.getHeader("Set-Cookie");
  if (!previous) res.setHeader("Set-Cookie", cookie);
  else if (Array.isArray(previous)) res.setHeader("Set-Cookie", previous.concat(cookie));
  else res.setHeader("Set-Cookie", [previous, cookie]);
}

function cookieString(name, value, options) {
  const parts = [name + "=" + encodeURIComponent(value), "Path=/"];
  if (options && options.maxAge != null) parts.push("Max-Age=" + Math.floor(options.maxAge));
  if (options && options.httpOnly) parts.push("HttpOnly");
  parts.push("SameSite=" + ((options && options.sameSite) || "Lax"));
  if (options && options.secure) parts.push("Secure");
  return parts.join("; ");
}

/* ---------------------------------------------------------------------- ip */

function clientIp(req) {
  if (config.trustProxy) {
    const forwarded = String(req.headers["x-forwarded-for"] || "").split(",")[0].trim();
    if (forwarded) return forwarded;
  }
  return (req.socket && req.socket.remoteAddress) || "unknown";
}

/* -------------------------------------------------------------- rate limit */

const rateBuckets = new Map();

function rateLimit(bucket, key, max, windowMs) {
  const id = bucket + ":" + key;
  const now = Date.now();
  let entry = rateBuckets.get(id);
  if (!entry || entry.reset <= now) {
    entry = { count: 0, reset: now + windowMs };
    rateBuckets.set(id, entry);
  }
  entry.count += 1;
  return entry.count <= max;
}

setInterval(() => {
  const now = Date.now();
  for (const [key, entry] of rateBuckets) {
    if (entry.reset <= now) rateBuckets.delete(key);
  }
}, 10 * 60 * 1000).unref();

/* ------------------------------------------------------------------- owner */

function seedOwner() {
  const owner = db.prepare("SELECT * FROM users WHERE role = 'owner' LIMIT 1").get();
  const configuredHash = config.ownerPasswordHash || null;

  if (owner) {
    if (owner.username !== config.ownerUsername) {
      db.prepare("UPDATE users SET username = ? WHERE id = ?").run(config.ownerUsername, owner.id);
    }
    if (configuredHash && (!owner.password_hash || owner.status === "setup")) {
      db.prepare("UPDATE users SET password_hash = ?, status = 'active' WHERE id = ?").run(
        configuredHash,
        owner.id
      );
    }
    return db.prepare("SELECT * FROM users WHERE role = 'owner' LIMIT 1").get();
  }

  db.prepare(
    "INSERT INTO users (username, email, password_hash, role, status, created_at) VALUES (?, NULL, ?, 'owner', ?, ?)"
  ).run(
    config.ownerUsername,
    configuredHash,
    configuredHash ? "active" : "setup",
    nowIso()
  );

  return db.prepare("SELECT * FROM users WHERE role = 'owner' LIMIT 1").get();
}

/* ------------------------------------------------------------------ status */

function licenseStatus(license) {
  if (!license) return "missing";
  if (license.revoked_at || license.status === "revoked") return "revoked";
  if (license.expires_at && license.expires_at <= nowIso()) return "expired";
  return license.status || "active";
}

function inviteStatus(invite) {
  if (!invite) return "missing";
  if (invite.revoked_at) return "revoked";
  if (invite.used_at) return "used";
  if (invite.expires_at && invite.expires_at <= nowIso()) return "expired";
  return "active";
}

